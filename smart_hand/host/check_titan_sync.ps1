$ErrorActionPreference = 'Stop'

$canonicalRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\titan_rtthread')).Path
$studioRoot = Join-Path $StudioProject 'src'
# All project-owned runtime sources/headers required by the UART path.
$fileNames = @(
    'smart_hand_protocol.c',
    'smart_hand_protocol.h',
    'smart_hand_uart.c',
    # smart_hand_uart.c includes this header and calls its AITRUST encoder, but
    # neither file was listed, so the one automated artefact gate could not see
    # them: a repo-side edit left unsynced would still print "check passed".
    'smart_hand_status_telemetry.c',
    'smart_hand_status_telemetry.h',
    'smart_hand_vision_state.c',
    'smart_hand_vision_state.h',
    'smart_hand_sequence_guard.c',
    'smart_hand_sequence_guard.h',
    'titan_trust_model.c',
