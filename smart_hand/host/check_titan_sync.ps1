    'voice_app.c',
    'voice_app.h',
    'voice_app_titan.c',
    'voice_app_titan.h'
)

if (-not (Test-Path -LiteralPath $studioRoot -PathType Container)) {
    throw "RT-Thread Studio source directory not found: $studioRoot"
}

$mismatchFound = $false
$results = foreach ($fileName in $fileNames) {
    $canonicalPath = Join-Path $canonicalRoot $fileName
    $studioPath = Join-Path $studioRoot $fileName
    if (-not (Test-Path -LiteralPath $canonicalPath -PathType Leaf)) {
        throw "Canonical source file not found: $canonicalPath"
    }
    if (-not (Test-Path -LiteralPath $studioPath -PathType Leaf)) {
        throw "Studio source file not found: $studioPath"
    }

    $canonicalHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $canonicalPath).Hash
    $studioHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $studioPath).Hash
    $matches = $canonicalHash -eq $studioHash
    if (-not $matches) {
        $mismatchFound = $true
    }
    [pscustomobject]@{
        File = $fileName
        Match = $matches
        CanonicalSHA256 = $canonicalHash
        StudioSHA256 = $studioHash
    }
}

$results | Format-Table -AutoSize
if ($mismatchFound) {
    throw 'Titan source trees differ; inspect them before building or copying files.'
}
Write-Host 'Titan source sync check passed.'
Write-Host 'Note: hash match is not ARM link evidence; run check_titan_linkage.ps1 after Studio Build.'
